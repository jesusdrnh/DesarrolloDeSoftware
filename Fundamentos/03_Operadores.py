# Uso de operadores lógicos en Python
a = True
b = False

#en C#: && (AND), || (OR), ! (NOT) 
print("a AND b:", a and b)  # Operador AND
print("a OR b:", a or b)    # Operador OR
print("NOT a:", not a)      # Operador NOT

x = 10
y = 20

print("x + y:", x + y)    # Suma
print("x - y:", x - y)    # Resta
print("x * y:", x * y)    # Multiplicación
print("x / y:", x / y)    # División
print("x // y:", x // y)  # División entera
print("x % y:", x % y)    # Módulo
print("x ** y:", x ** y)  # Exponente

print("x & y:", x & y)    # AND bit a bit
print("x | y:", x | y)    # OR bit a bit

print("x > y:", x > y)    # Mayor que
print("x < y:", x < y)    # Menor que
print("x >= y:", x >= y)  # Mayor o igual que
print("x <= y:", x <= y)  # Menor o igual que

print("x == y:", x == y)  # Igual que
print("x != y:", x != y)  # Diferente que

print("x is y:", x is y)  # Identidad de objeto
print("x is not y:", x is not y)  # Identidad de objeto diferente

print("x in [10, 20, 30]:", x in [10, 20, 30])  # Pertenencia a una lista
print("x not in [10, 20, 30]:", x not in [10, 20, 30])  # No pertenencia a una lista

print("x in range(1, 11):", x in range(1, 11))  # Pertenencia a un rango
print("x not in range(1, 11):", x not in range(1, 11))  # No pertenencia a un rango


