# Declaración de variables y tipos de datos en Python
entero = 10  # Entero
flotante = 3.14  # Doble precisión (float en Python)
booleano = True  # Booleano
cadena = "Hola, Python!"  # Cadena de texto
character = 'A'  # Carácter (en Python se usa una cadena de un solo carácter)

print("Tipo de dato entero:", entero, type(entero))
print("Tipo de dato flotante:", flotante, type(flotante))
print("Tipo de dato booleano:", booleano, type(booleano))
print("Tipo de dato cadena:", cadena, type(cadena))
print("Tipo de dato caracter:", character, type(character))